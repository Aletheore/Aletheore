import json

from aletheore.dead_code import find_dead_code


def _unused(tmp_path):
    return {(e["package"], e.get("manifest")) for e in find_dead_code(tmp_path, [], None)["unused_dependencies"]}


def test_tool_named_in_scripts_or_config_is_not_unused(tmp_path):
    (tmp_path / "package.json").write_text(json.dumps({
        "scripts": {"lint": "eslint .", "test": "vitest run"},
        "devDependencies": {"eslint": "^9.0.0", "vitest": "^2.0.0", "left-pad": "^1.0.0", "@types/node": "^20.0.0"},
    }))
    (tmp_path / "index.js").write_text("console.log(1)\n")
    assert _unused(tmp_path) == {("left-pad", None)}


def test_tool_named_in_root_workflow_covers_nested_manifest(tmp_path):
    (tmp_path / ".github" / "workflows").mkdir(parents=True)
    (tmp_path / ".github" / "workflows" / "ci.yml").write_text("run: npx playwright test\n")
    (tmp_path / "web").mkdir()
    (tmp_path / "web" / "package.json").write_text(json.dumps({"devDependencies": {"playwright": "1.0.0", "unused-pkg": "1.0.0"}}))
    modules = [{"path": "web/a.js", "imports": []}]
    (tmp_path / "web" / "a.js").write_text("x\n")
    out = find_dead_code(tmp_path, modules, None)["unused_dependencies"]
    assert {e["package"] for e in out} == {"unused-pkg"}


def test_pip_compile_output_only_judges_project_declared_names(tmp_path):
    (tmp_path / "requirements.txt").write_text(
        "# This file was autogenerated by pip-compile\namqp==5.0\n    # via kombu\nflask==3.0\n"
    )
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "x"\ndependencies = ["flask"]\n')
    (tmp_path / "app.py").write_text("print(1)\n")
    modules = [{"path": "app.py", "imports": []}]
    out = {e["package"] for e in find_dead_code(tmp_path, modules, None)["unused_dependencies"]}
    assert "amqp" not in out


def test_tool_named_in_a_config_variant_or_mts_config_is_not_unused(tmp_path):
    (tmp_path / "package.json").write_text(json.dumps({
        "devDependencies": {"jsdom": "1.0.0", "vite": "1.0.0", "left-pad": "1.0.0"},
    }))
    (tmp_path / "vitest.config.mts").write_text("export default { test: { environment: 'jsdom' } }\n")
    (tmp_path / "vitest.config.build.ts").write_text("import { defineConfig } from 'vite'\n")
    (tmp_path / "index.js").write_text("x\n")
    assert _unused(tmp_path) == {("left-pad", None)}


def test_tool_called_from_an_extensionless_or_shell_script_is_not_unused(tmp_path):
    (tmp_path / "scripts").mkdir()
    (tmp_path / "scripts" / "lint").write_text("#!/bin/sh\nruff check .\n")
    (tmp_path / "scripts" / "docs.sh").write_text("mkdocs build\n")
    (tmp_path / "requirements.txt").write_text("ruff\nmkdocs\nleft-pad\n")
    (tmp_path / "app.py").write_text("x = 1\n")
    assert _unused(tmp_path) == {("left-pad", None)}
